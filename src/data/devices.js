/**
 * Search haystack: "Apple iPhone 15 Pro 2023".
 *
 * Deliberately excludes the category - every phone containing the word "phone"
 * lets stray query characters match there ("ip15p" would hit the p in "phone"
 * and rank plain iPhone 15 above iPhone 15 Pro). The list is grouped by
 * category in the UI, so typing it is not needed.
 */
export function searchText(device) {
  return `${device.brand} ${device.name} ${device.year}`;
}

export const DEVICE_BY_ID = new Map(DEVICES.map((d) => [d.id, d]));

/** Newest first when relevance ties. */
export const byYearDesc = (a, b) => b.year - a.year;

/** Typing a device's full name should select that device, not a longer sibling. */
export function exactNameBoost(device, query) {
  const q = query.trim().toLowerCase();
  if (!q) return 0;
  return q === device.name.toLowerCase() ||
    q === `${device.brand} ${device.name}`.toLowerCase()
    ? 1000
    : 0;
}
