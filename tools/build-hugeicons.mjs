/**
 * Generates src/data/icons.js from @hugeicons/core-free-icons (MIT).
 *
 * The package ships icon definitions as React-style node arrays; the extension
 * needs plain SVG markup, so attribute names are converted from camelCase to
 * kebab-case and the nodes are serialised into an inner-SVG string per icon.
 *
 * Run: node tools/build-hugeicons.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Semantic name in the UI -> icon export in the Hugeicons free package. */
const ICON_MAP = {
  brand: 'ComputerPhoneSyncIcon',
  device: 'SmartPhone01Icon',
  star: 'StarIcon',
  refresh: 'RefreshIcon',
  rotate: 'OrientationPotraitToLandscapeIcon',
  camera: 'Camera01Icon',
  external: 'LinkSquare02Icon',
  statusbar: 'SidebarTopIcon',
  back: 'ArrowLeft01Icon',
  forward: 'ArrowRight01Icon',
  add: 'PlusSignIcon',
  close: 'Cancel01Icon',
  compare: 'LayoutTwoColumnIcon',
  syncScroll: 'Link04Icon',
  settings: 'Settings01Icon',
  accurate: 'DashboardSpeed02Icon',
  session: 'Key01Icon',
  warning: 'Alert02Icon',
  record: 'RecordIcon',
  stop: 'StopIcon',
  // Simulated device status-bar glyphs.
  signal: 'FullSignalIcon',
  wifi: 'Wifi02Icon',
  battery: 'BatteryFullIcon',
};

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const escapeAttr = (v) =>
  String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

async function toMarkup(exportName) {
  const { default: nodes } = await import(`@hugeicons/core-free-icons/${exportName}`);
  return nodes
    .map(([tag, attrs]) => {
      const pairs = Object.entries(attrs)
        .filter(([key]) => key !== 'key')
        .map(([key, value]) => `${kebab(key)}="${escapeAttr(value)}"`);
      return `<${tag} ${pairs.join(' ')}/>`;
    })
    .join('');
}

const entries = {};
for (const [name, exportName] of Object.entries(ICON_MAP)) {
  entries[name] = await toMarkup(exportName);
}

const banner = `// Generated by tools/build-hugeicons.mjs - do not edit by hand.
//
// Artwork from Hugeicons (https://hugeicons.com), free set, MIT licensed.
// Each value is the inner markup of a 24x24 viewBox icon using currentColor.
//
// Source exports:
${Object.entries(ICON_MAP)
  .map(([name, exportName]) => `//   ${name.padEnd(9)} <- ${exportName}`)
  .join('\n')}
`;

fs.writeFileSync(
  path.join(ROOT, 'src', 'data', 'icons.js'),
  `${banner}\nexport const ICONS = ${JSON.stringify(entries, null, 2)};\n`,
);

console.log(`wrote src/data/icons.js with ${Object.keys(entries).length} icons`);
